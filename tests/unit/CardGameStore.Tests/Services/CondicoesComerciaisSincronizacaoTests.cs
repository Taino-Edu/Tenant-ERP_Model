        (await db.TenantCharges.AsNoTracking().SingleAsync()).Amount.Should().Be(120m);
    }

    [Fact]
    public async Task Renegociacao_DiaDeVencimento_MoveACobrancaEmAberto()
    {
        using var db = CreateDb();
        var tenant = await LojaAsync(db);
        var (billing, condicoes) = Servicos(db);
        await billing.GerarMensalidadesAsync(MesAtual);

        await condicoes.AtualizarAsync(tenant.Id, Condicoes(tenant, r => r.DiaVencimento = 25));

        (await db.TenantCharges.AsNoTracking().SingleAsync()).DueDate.Day.Should().Be(25);
    }

    [Fact]
    public async Task Renegociacao_MenosParcelas_RedistribuiERemoveASobra()
    {
        using var db = CreateDb();
        var tenant = await LojaAsync(db, mensalidade: 0m);
        var (billing, condicoes) = Servicos(db);

        // 4 parcelas a partir do mês passado: a 1ª já foi paga, a 2ª (deste mês) está em aberto.
        tenant.SetupFee = 400m;
        tenant.SetupInstallments = 4;
        tenant.SetupFirstDueDate = MesAtual.AddMonths(-1).AddDays(4);
        await db.SaveChangesAsync();
        await billing.GerarMensalidadesAsync(MesAtual);

        var primeira = await db.TenantCharges.SingleAsync(c => c.InstallmentNumber == 1);
        primeira.PaidAt = MesAtual.AddMonths(-1).AddDays(4);
        await db.SaveChangesAsync();

        var resultado = await condicoes.AtualizarAsync(tenant.Id, Condicoes(tenant, r => r.ImplantacaoParcelas = 2));

        resultado.Cobrancas.Pendencias.Should().BeEmpty();
        var parcelas = await db.TenantCharges.AsNoTracking().OrderBy(c => c.InstallmentNumber).ToListAsync();
        parcelas.Select(c => (c.InstallmentNumber!.Value, c.Amount, c.InstallmentCount!.Value))
            .Should().Equal((1, 100m, 4), (2, 300m, 2));
    }

    [Fact]
    public async Task Renegociacao_ImplantacaoAbaixoDoJaPago_EhRecusada()
    {
        using var db = CreateDb();
        var tenant = await LojaAsync(db, mensalidade: 0m);
        tenant.SetupFee = 400m;
        tenant.SetupInstallments = 2;
        tenant.SetupFirstDueDate = MesAtual.AddDays(4);
        db.TenantCharges.Add(new TenantCharge
        {
            TenantId = tenant.Id, Kind = TenantChargeKind.Implantacao, Amount = 200m, InstallmentNumber = 1,
            InstallmentCount = 2, ReferenceMonth = MesAtual, DueDate = MesAtual.AddDays(4),
            PaidAt = MesAtual.AddDays(1), AutoGenerated = true,
        });
        await db.SaveChangesAsync();

        var acao = () => Servicos(db).Condicoes.AtualizarAsync(tenant.Id, Condicoes(tenant, r => r.ImplantacaoValor = 150m));

        await acao.Should().ThrowAsync<InvalidOperationException>().WithMessage("*já foram pagos*");
    }

    [Fact]
    public async Task Previa_MostraDescontoAcabandoEParcelas()
    {
        using var db = CreateDb();
        var tenant = await LojaAsync(db);
        tenant.SetupFee = 300m;
        tenant.SetupInstallments = 3;
        tenant.SetupFirstDueDate = MesAtual.AddMonths(1).AddDays(4);
        await db.SaveChangesAsync();

        var condicoes = Servicos(db).Condicoes;
        var dto = (await condicoes.CriarDescontoAsync(tenant.Id,
            Desconto("ValorFixo", 50m, MesAtual, MesAtual.AddMonths(1)), "Taino")).Condicoes;

        dto.Previa.Should().HaveCount(12);
        dto.Previa[0].Itens.Should().ContainSingle(i => i.Tipo == "Mensalidade").Which.Situacao.Should().Be("EmAberto");
        dto.Previa[0].Total.Should().Be(150m);
        dto.Previa[1].Total.Should().Be(150m + 100m, "último mês do desconto e primeira parcela");
        dto.Previa[2].Total.Should().Be(200m + 100m);
        dto.Previa[4].Total.Should().Be(200m);
        dto.Descontos.Should().ContainSingle().Which.CriadoPor.Should().Be("Taino");
    }

