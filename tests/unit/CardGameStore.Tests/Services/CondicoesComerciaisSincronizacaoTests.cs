    [Fact]
    public async Task ExcluirCobrancaEmitida_CancelaNoGatewayAntes()
    {
        using var db = CreateDb();
        var tenant = await LojaAsync(db);
        var gateway = new GatewayFalso();
        db.TenantCharges.Add(new TenantCharge
        {
            TenantId = tenant.Id, Kind = TenantChargeKind.Mensalidade, Amount = 200m,
            ReferenceMonth = MesAtual.AddMonths(-1), DueDate = MesAtual.AddMonths(-1).AddDays(9),
            Gateway = gateway.Name, ExternalChargeId = "pay_mes_passado",
        });
        await db.SaveChangesAsync();

        var cobranca = await db.TenantCharges.SingleAsync();
        await Servicos(db, gateway).Billing.ExcluirCobrancaAsync(cobranca.Id);

        gateway.Canceladas.Should().Equal("pay_mes_passado");
        (await db.TenantCharges.AnyAsync()).Should().BeFalse();
    }

    private sealed class GatewayFalso : IPlatformPaymentGateway
    {
        public bool RecusarCancelamento { get; init; }
        public List<string> Canceladas { get; } = new();

        public string Name => "teste";
        public bool IsConfigured => true;

        public Task<string> GarantirClienteAsync(Tenant tenant, CancellationToken ct = default) => Task.FromResult("cus_teste");

        public Task<CobrancaGatewayResult> EmitirCobrancaAsync(TenantCharge charge, Tenant tenant, CancellationToken ct = default) =>
            Task.FromResult(new CobrancaGatewayResult($"pay_{charge.Id:N}", null));

        public Task CancelarCobrancaAsync(string externalChargeId, CancellationToken ct = default)
        {
            if (RecusarCancelamento) throw new InvalidOperationException("Asaas recusou o cancelamento (400).");
            Canceladas.Add(externalChargeId);
            return Task.CompletedTask;
        }

        public bool ValidarAutenticacao(string? tokenRecebido) => true;
        public GatewayWebhookNotification? InterpretarWebhook(JsonElement payload) => null;
    }
}
